require("dotenv").config();
const express = require("express");
const cors = require("cors");
const path = require("path");
const fs = require("fs");
const authRoutes = require("./routes/auth");
const blogRoutes = require("./routes/blogs");
const app = express();
const PORT = process.env.PORT || 5000;
app.use(cors({ origin: process.env.CLIENT_ORIGIN ? process.env.CLIENT_ORIGIN.split(",") : true }));
app.use(express.json({ limit: "1mb" }));
app.get("/api/health", (req,res)=>res.json({status:"ok",message:"InkSpace API is running"}));
app.use("/api/auth", authRoutes);
app.use("/api/blogs", blogRoutes);
app.use((req,res)=>res.status(404).json({message:"Route not found"}));
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({message:"Server error"});});
const dataDir=path.join(__dirname,"data");
if(!fs.existsSync(dataDir)) fs.mkdirSync(dataDir,{recursive:true});
for(const file of ["users.json","blogs.json"]){const p=path.join(dataDir,file);if(!fs.existsSync(p))fs.writeFileSync(p,"[]");}
app.listen(PORT,()=>console.log(`InkSpace API running at http://localhost:${PORT}`));
